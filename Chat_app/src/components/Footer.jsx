import { memo } from 'react'
import { useNavigate, useLocation } from 'react-router-dom'
import Avatar from './Avatar'

// Bottom navigation: Settings (left), Chats/groups (center),
// and the profile avatar at the right corner.
function Footer({ userName = 'You' }) {
  const navigate = useNavigate()
  const { pathname } = useLocation()

  const isActive = (path) =>
    path === '/rooms' ? pathname.startsWith('/rooms') : pathname === path

  return (
    <nav className="footer-nav" aria-label="Primary">
      <button
        className={`nav-btn ${isActive('/settings') ? 'is-active' : ''}`}
        onClick={() => navigate('/settings')}
        aria-label="Settings"
        title="Settings"
      >
        <GearIcon />
      </button>

      <button
        className={`nav-btn nav-btn--primary ${isActive('/rooms') ? 'is-active' : ''}`}
        onClick={() => navigate('/rooms')}
        aria-label="Chats"
        title="Chats"
      >
        <ChatIcon />
      </button>

      <button
        className="nav-profile"
        onClick={() => navigate('/profile')}
        aria-label="Profile"
        title="Profile"
      >
        <Avatar name={userName} size={40} />
      </button>
    </nav>
  )
}

function GearIcon() {
  return (
    <svg viewBox="0 0 24 24" width="22" height="22" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
      <circle cx="12" cy="12" r="3" />
      <path d="M19.4 15a1.65 1.65 0 0 0 .33 1.82l.06.06a2 2 0 1 1-2.83 2.83l-.06-.06a1.65 1.65 0 0 0-1.82-.33 1.65 1.65 0 0 0-1 1.51V21a2 2 0 0 1-4 0v-.09A1.65 1.65 0 0 0 9 19.4a1.65 1.65 0 0 0-1.82.33l-.06.06a2 2 0 1 1-2.83-2.83l.06-.06a1.65 1.65 0 0 0 .33-1.82 1.65 1.65 0 0 0-1.51-1H3a2 2 0 0 1 0-4h.09A1.65 1.65 0 0 0 4.6 9a1.65 1.65 0 0 0-.33-1.82l-.06-.06a2 2 0 1 1 2.83-2.83l.06.06a1.65 1.65 0 0 0 1.82.33H9a1.65 1.65 0 0 0 1-1.51V3a2 2 0 0 1 4 0v.09a1.65 1.65 0 0 0 1 1.51 1.65 1.65 0 0 0 1.82-.33l.06-.06a2 2 0 1 1 2.83 2.83l-.06.06a1.65 1.65 0 0 0-.33 1.82V9a1.65 1.65 0 0 0 1.51 1H21a2 2 0 0 1 0 4h-.09a1.65 1.65 0 0 0-1.51 1z" />
    </svg>
  )
}

function ChatIcon() {
  return (
    <svg viewBox="0 0 24 24" width="22" height="22" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
      <path d="M21 11.5a8.38 8.38 0 0 1-.9 3.8 8.5 8.5 0 0 1-7.6 4.7 8.38 8.38 0 0 1-3.8-.9L3 21l1.9-5.7a8.38 8.38 0 0 1-.9-3.8 8.5 8.5 0 0 1 4.7-7.6 8.38 8.38 0 0 1 3.8-.9h.5a8.48 8.48 0 0 1 8 8v.5z" />
    </svg>
  )
}

export default memo(Footer)
